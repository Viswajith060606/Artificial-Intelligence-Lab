if __name__ == "__main__":
    g = GraphDFS()

    # Constructing an example directed graph:
    # 0 -> 1, 0 -> 2
    # 1 -> 3, 1 -> 4
    # 2 -> 5
    # 4 -> 5
    g.add_edge(0, 1)
    g.add_edge(0, 2)
    g.add_edge(1, 3)
    g.add_edge(1, 4)
    g.add_edge(2, 5)
    g.add_edge(4, 5)

    start = 0
    goal = 5

    print("=== Depth-First Search (DFS) Implementation ===")

    # 1. Recursive DFS Traversal
    rec_order = g.dfs_recursive(start)
    print(f"DFS Traversal (Recursive) starting from {start}: {rec_order}")

    # 2. Iterative DFS Traversal
    iter_order = g.dfs_iterative(start)
    print(f"DFS Traversal (Iterative) starting from {start}: {iter_order}")

    # 3. Path Finding
    path = g.dfs_find_path(start, goal)
    if path:
        print(f"DFS Path from {start} to {goal}: {' -> '.join(map(str, path))}")
    else:
        print(f"No path exists between {start} and {goal}.")