from collections import deque

# ==========================================
# 1. AI GRAPH SEARCH AGENT (BFS)
# ==========================================

class GraphBFS:
    def __init__(self):
        # Adjacency List representation of the graph
        self.graph = {}

    def add_edge(self, u, v):
        """Adds a directed edge from node u to node v."""
        if u not in self.graph:
            self.graph[u] = []
        if v not in self.graph:
            self.graph[v] = []
        self.graph[u].append(v)

    def bfs_traversal(self, start_node):
        """
        Performs standard BFS traversal from a start node.
        Visits all nodes level-by-level.
        """
        visited = set()
        queue = deque([start_node])
        visited.add(start_node)

        traversal_order = []

        while queue:
            # Dequeue a vertex from front of queue
            current_node = queue.popleft()
            traversal_order.append(current_node)

            # Get all adjacent vertices of current_node
            for neighbor in self.graph.get(current_node, []):
                if neighbor not in visited:
                    visited.add(neighbor)
                    queue.append(neighbor)

        return traversal_order

    def bfs_shortest_path(self, start_node, target_node):
        """
        Finds the shortest path between start_node and target_node using BFS.
        Returns the path as a list of nodes.
        """
        if start_node not in self.graph or target_node not in self.graph:
            return None

        # Queue stores tuples of (current_node, path_taken)
        queue = deque([(start_node, [start_node])])
        visited = set([start_node])

        while queue:
            current_node, path = queue.popleft()

            # Goal Test
            if current_node == target_node:
                return path

            # Expand Neighbors
            for neighbor in self.graph.get(current_node, []):
                if neighbor not in visited:
                    visited.add(neighbor)
                    queue.append((neighbor, path + [neighbor]))

        return None  # No path found


