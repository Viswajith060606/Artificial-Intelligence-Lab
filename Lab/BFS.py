# 2. MAIN EXECUTION & EXAMPLE
# ==========================================

if __name__ == "__main__":
    g = GraphBFS()

    # Constructing an example graph:
    # 0 -> 1, 0 -> 2
    # 1 -> 3, 1 -> 4
    # 2 -> 4, 2 -> 5
    # 3 -> 5
    g.add_edge(0, 1)
    g.add_edge(0, 2)
    g.add_edge(1, 3)
    g.add_edge(1, 4)
    g.add_edge(2, 4)
    g.add_edge(2, 5)
    g.add_edge(3, 5)

    start = 0
    goal = 5

    print("=== Breadth-First Search (BFS) Implementation ===")

    # 1. Full Traversal
    order = g.bfs_traversal(start)
    print(f"BFS Traversal starting from node {start}: {order}")

    # 2. Shortest Path Finding
    path = g.bfs_shortest_path(start, goal)
    if path:
        print(f"Shortest Path from {start} to {goal}: {' -> '.join(map(str, path))}")
    else:
        print(f"No path exists between {start} and {goal}.")